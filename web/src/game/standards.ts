/** "3.NF.A.3.d" and "3.NF.A.3d" mean the same code. */
export const normalize = (code: string) => code.replace(/\.([a-d])$/, "$1");

/**
 * Standards (for the given code prefixes, e.g. ["K"], ["5", "6", "7"], ["HSA", "HSN-RN"] or ["CALC"]) that no
 * level teaches and that aren't listed as not covered.
 */
export function missingStandards(
  worlds: World[],
  notCovered: { code: string; why: string }[],
  grades: string[],
): string[] {
  const taught = new Set(worlds.flatMap((w) => w.levels.flatMap((l) => l.standards.map(normalize))));
  const skipped = new Set(notCovered.filter((n) => n.why.trim()).map((n) => normalize(n.code)));
  // "K" or "3" means that grade's math (K.CC.A.1); "HSA" or "MS-PS1" also takes dashed codes (HSA-SSE…, MS-PS1-4).
  const dashed = (p: string) => p.startsWith("HS") || p.includes("-PS");
  const matches = (code: string, p: string) =>
    code === p || code.startsWith(p.endsWith(".") ? p : `${p}.`) || (dashed(p) && code.startsWith(`${p}-`));
  return STANDARDS.filter((s) => grades.some((p) => matches(s.code, p)))
    .map((s) => s.code)
    .filter((code) => !taught.has(code) && !skipped.has(code));
}

/** Codes a level claims that aren't real standards (typos). */
export function unknownStandards(worlds: World[]): string[] {
  const known = new Set(STANDARDS.map((s) => s.code));
  return worlds.flatMap((w) => w.levels.flatMap((l) => l.standards.map(normalize))).filter((c) => !known.has(c));
}
